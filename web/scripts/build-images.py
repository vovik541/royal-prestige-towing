"""Crop the client's original photos and export responsive WebP derivatives.

Reads the untouched originals from the repository root (phone screenshots with black
letterbox bars) and writes to web/public/images/photos/:
    <id>-<width>.webp at up to 480 / 800 / 1200 px wide (never upscaled; the largest is
    capped at the source width), a 1200x630 JPEG for social sharing, and
    src/app/content/photo-sizes.ts with the real pixel sizes.

Run from web/:  python scripts/build-images.py
"""
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[2]
OUT = Path(__file__).resolve().parents[1] / "public" / "images" / "photos"
MANIFEST = Path(__file__).resolve().parents[1] / "src" / "app" / "content" / "photo-sizes.ts"
WIDTHS = (480, 800, 1200)
QUALITY = 80

# id: (original file, extra trim (left, top, right, bottom) applied after the letterbox crop)
PHOTOS = {
    "lamborghini-urus":   ("IMG_20261022_223519.jpg", (0, 0, 0, 0)),
    "volvo-c70":          ("IMG_20261022_223521.jpg", (0, 0, 0, 0)),
    "milling-machine":    ("IMG_20261022_223527.jpg", (0, 0, 0, 0)),
    "lathe-forklift":     ("IMG_20261022_223529.jpg", (0, 0, 0, 0)),
    "lathe-secured":      ("IMG_20261022_223533.jpg", (0, 0, 52, 0)),  # phone UI tab on the right edge
    "vintage-microtruck": ("IMG_20261022_223537.jpg", (0, 0, 0, 0)),
    "mclaren-side":       ("IMG_20261022_223541.jpg", (0, 0, 0, 0)),
    "mclaren-front":      ("IMG_20261022_223545.jpg", (0, 0, 0, 0)),
    "mclaren-rear":       ("IMG_20261022_223549.jpg", (0, 0, 0, 0)),
    "cargo-van":          ("IMG_20261022_223553.jpg", (0, 0, 0, 0)),
    "vw-beetle":          ("IMG_20261022_223558.jpg", (0, 0, 0, 0)),
    "bmw-alpina":         ("IMG_20261022_223602.jpg", (0, 0, 0, 0)),
    "mercedes-sedan":     ("IMG_20261022_223606.jpg", (0, 0, 0, 0)),
    "owner-serhii":       ("sergei.jpg", (0, 0, 0, 0)),
}


def letterbox_crop(im: Image.Image) -> Image.Image:
    """Remove the black bars above and below the photo (and a 3px safety margin)."""
    gray = im.convert("L")
    w, h = gray.size
    px = gray.load()

    def row_mean(y: int) -> float:
        return sum(px[x, y] for x in range(0, w, 5)) / (w / 5)

    top = next(y for y in range(h) if row_mean(y) > 14)
    bottom = next(y for y in range(h - 1, -1, -1) if row_mean(y) > 14)
    return im.crop((3, top + 3, w - 3, bottom - 2))


def portrait_crop(im: Image.Image) -> Image.Image:
    """Head-and-shoulders 4:5 crop of the owner's selfie (face sits ~30% from the top)."""
    w, h = im.size
    ch = round(w * 5 / 4)
    top = max(0, min(h - ch, round(h * 0.12)))
    return im.crop((0, top, w, top + ch))


def save_set(photo_id: str, im: Image.Image) -> list[tuple[int, int]]:
    """Write one WebP per width, never upscaling; files are named by their real width."""
    sizes: list[tuple[int, int]] = []
    for target in WIDTHS:
        width = min(target, im.width)
        if sizes and sizes[-1][0] == width:
            continue
        out = im if width == im.width else im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
        out.save(OUT / f"{photo_id}-{out.width}.webp", "WEBP", quality=QUALITY, method=6)
        sizes.append((out.width, out.height))
    return sizes


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.webp"):
        old.unlink()
    manifest: dict[str, list[tuple[int, int]]] = {}
    for photo_id, (src, (l, t, r, b)) in PHOTOS.items():
        im = ImageOps.exif_transpose(Image.open(ROOT / src)).convert("RGB")
        im = letterbox_crop(im)
        im = im.crop((l, t, im.width - r, im.height - b))
        if photo_id == "owner-serhii":
            im = portrait_crop(im)
        sizes = save_set(photo_id, im)
        manifest[photo_id] = sizes
        print(photo_id, "->", sizes)

    # Social sharing image (JPEG for the widest crawler support)
    og = letterbox_crop(Image.open(ROOT / "IMG_20261022_223541.jpg").convert("RGB"))
    og = ImageOps.fit(og, (1200, 630), Image.LANCZOS, centering=(0.5, 0.6))
    og.save(OUT.parent / "og-default.jpg", "JPEG", quality=84, optimize=True, progressive=True)
    print("og-default.jpg 1200x630")

    lines = [
        "// Generated by scripts/build-images.py. Do not edit by hand.",
        "// Real pixel sizes of every WebP derivative in public/images/photos.",
        "export const PHOTO_SIZES = {",
    ]
    for pid, sizes in manifest.items():
        lines.append(f"  '{pid}': [" + ", ".join(f"[{w}, {h}]" for w, h in sizes) + "],")
    lines.append("} as const;")
    lines.append("")
    lines.append("export type PhotoId = keyof typeof PHOTO_SIZES;")
    MANIFEST.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", MANIFEST.relative_to(ROOT))


if __name__ == "__main__":
    main()
